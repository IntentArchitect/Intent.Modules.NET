                    ## Step 2 — Parse the Menu Description Into Items

                    The context you are given is the single source of truth.

                    Rules:

                    - Generate menu items ONLY from the provided context (free-text menu description) or from the modeled `Navigation Target End` context attached to each file.
                    - The sample files in this folder are structural/layout examples only. They demonstrate _how_ to render items, not _which_ items must exist.
                    - Do not invent or preserve “standard” items by convention (including account/auth items) unless they are present in the context for the region you are populating.

                    The context you're given will be prose, not a formal schema, along the lines of:

                    > "The sider menu consists of the following:
                    >
                    > - a navigation link to the product list page with route `/product-list`
                    > - a navigation link to the order list page with route `/order-list` which requires roles `Admin` or `Write`"

                    For each described link, extract:

                    | Field             | How to extract                                                                                                          | Default if unstated                                            |
                    | ----------------- | ----------------------------------------------------------------------------------------------------------------------- | -------------------------------------------------------------- |
                    | **Label**         | The page/entity name mentioned (title-case it: "product list" → "Product List")                                         | Required — ask if truly ambiguous                              |
                    | **Href**          | The literal route given (e.g. `` `/product-list` ``)                                                                    | Required                                                       |
                    | **Section**       | Explicit mention of "header", "sider"/"side menu", "footer", or "profile"/"account menu"                                | **Sider**                                                      |
                    | **Icon**          | Only if explicitly described (e.g. "with a home icon") — map to the closest `Icons.Material.Filled.*` member            | None — omit the `Icon` attribute entirely rather than guessing |
                    | **Authorization** | Phrases like "requires roles `X` or `Y`", "requires policy `X`", "for logged-in users only" / "requires authentication" | None (item renders unconditionally)                            |

                    - _Model-derived invocation:_* when this skill runs because a `Navigation Target End` changed rather than because of a typed request, the item list isn't prose you're handed directly — it's the AI Context Software Factory attached to each scaffolded file (`MainLayoutHeader.razor`, `MainLayoutSider.razor`, `MainLayoutFooter.razor`, the Profile menu file), in the exact same "a navigation link to the X with route 'Y' [with required role(s)/policies...]" phrasing as the example above. Parse it with the identical rules in the table above — the `Regions` value on each `Navigation Target End` is what already routed that item's context to the right file.

                    Authorization phrase mapping:

                    - "requires roles `A` or `B`" → gate with `Roles="A,B"` (comma-joined, see Step 4 — `AuthorizeView.Roles` is a single comma-delimited string, not a collection)
                    - "requires policy `X`" → gate with `Policy="X"`
                    - "for logged-in users" / "requires authentication" / "requires login" with no roles/policy → gate with a bare `<AuthorizeView>` (no `Roles`/`Policy` attribute — matches any authenticated user)
                    - No authorization language at all → do not wrap the item in anything

                    If the target project is **NoAuth** (per Step 1) and the context nonetheless describes a role/policy/login requirement for an item: render the item **unconditionally** anyway (there is no auth infrastructure to gate it with) and say so plainly in your response — do not silently drop the item, and do not add `AddAuthorizationCore`/`AddCascadingAuthenticationState` to `Program.cs` to make the gating "work". That is a much bigger change than a menu edit and is out of scope for this skill.

