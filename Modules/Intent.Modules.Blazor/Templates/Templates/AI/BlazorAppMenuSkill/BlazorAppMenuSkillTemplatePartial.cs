                    ## Step 4 — Populate `MainLayoutHeader.razor`

                    Follow `app-header-auth-sample.razor`. Three independent concerns live in this file — do not conflate them:

                    1. **Fixed chrome — preserve exactly as-is, in both Auth and NoAuth projects**: the drawer-toggle (`<span onclick="navDrawer.toggle()"><MudIconButton Icon="@Icons.Material.Filled.Menu" Color="Color.Inherit" Edge="Edge.Start" /></span>`), the brand `MudButton`, `MudSpacer`, and a bare `<ThemeToggle />`. None of these carry `OnClick`/`OnToggle` `EventCallback` parameters in the current scaffold — do not add any; the drawer opens via `navDrawer.toggle()` JS interop and the theme toggles internally, with no code-behind wiring in `MainLayoutHeader.razor.cs`.
                    2. **The Profile component slot** — if the Layout has a modeled Profile Menu element (i.e. its file, e.g. `MainLayoutProfile.razor`, exists per the MANDATORY read above), `MainLayoutHeader.razor` must include an unconditional reference to it (e.g. `<MainLayoutProfile />`), placed after `ThemeToggle`. This holds in both Auth and NoAuth projects, and regardless of whether the Profile menu currently has any modeled nav items — in an Auth project the Profile component is also what shows Login/Register when signed out, so it's always meaningful even when empty of navigation links. **Never** wrap this reference in `<AuthorizeView>` here — any auth-based branching for the Profile surface lives entirely inside the Profile file itself (Step 6), never in the Header. If the file still has the raw scaffolded placeholder tag instead of a real component reference, fix it to reference the actual Profile component.
                    3. **Any Header-placed nav items** the context describes: render as `<MudButton Href="..." Color="Color.Inherit">Label</MudButton>` (MudAppBar is not a `MudNavMenu`, so `MudNavLink` doesn't fit here), positioned between the brand button and `<MudSpacer />`. Gate exactly like a Sider item (Step 3's `AuthorizeView` rules), in a NoAuth project never gate at all.

                    ### Region source-of-truth and "mandatory" sync (CRITICAL)

                    Only add/ensure header nav items that the context explicitly assigns to the Header section.

                    Rules:

                    - If the context does not mention any header items, do not add new header navigation buttons.
                    - Do not mirror Sider items into the Header by convention.
                    - Only prevent duplicates within the Header itself.

