                    ## Purpose

                    Every Blazor project generated by this solution's Intent Architect module has a `MainLayout.razor` that is intentionally thin — it just composes `<MainLayoutHeader/>`, `<MainLayoutSider/>`, `@Body` (plus `<MainLayoutFooter/>` when a Footer is modeled), inside whatever provider/wrapper markup (e.g. `<MudLayout>`, `<MudMainContent>`) the first scaffold generation used. The actual menu content lives as **literal, hand-authored markup** inside those component files, plus (when a Profile Menu element is modeled) a Profile menu component composed into the Header. There is deliberately **no shared nav-item data model** — never a `NavItem`/`AppNav` list feeding a generic loop.

