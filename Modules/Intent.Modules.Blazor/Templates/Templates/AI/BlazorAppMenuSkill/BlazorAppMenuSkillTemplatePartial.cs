                    ## Step 6 — Populate the Profile Menu file (e.g. `MainLayoutProfile.razor`)

                    This file only exists when `MainLayout` has a modeled **Profile Menu** child element (visible alongside Header/Sider/Footer in the User Interface designer) — if there is none, there is no Profile menu and this step doesn't apply. When present, it's scaffolded exactly like Steps 3-5: a Razor file (named `{Layout name}{Profile Menu element name}.razor`, e.g. `MainLayoutProfile.razor`, colocated with the other layout files per the path rules in "MANDATORY" above) generated once with `OverwriteDisabled`, with a bare, self-closing `<UserMenu />` placeholder as its only content — from then on you own filling it in.

                    `UserMenu` is a shared presentational component shipped from the UI-component library (not auth-specific — it carries no auth knowledge itself): a circuit-free `<details>`-based dropdown taking a `Title` (string, defaults to "Account menu"), a `Trigger` render fragment (the closed-state icon/content), and a `ChildContent` render fragment (the dropdown's items). It works identically on static-SSR Account pages and interactive pages.

                    **MANDATORY**: Any generated `<UserMenu>` markup MUST include a `<Trigger>...</Trigger>` node (as shown in `app-user-menu-auth-sample.razor`). The trigger is not optional; without it the menu surface is incomplete and may render incorrectly.


                    This menu is populated from `Navigation Target End`s whose `Layout Placement` -> `Regions` is set to `Profile`. It's primarily meant for profile/account-related pages (e.g. "My Profile", "Settings"), but it can hold any navigable page the context/model assigns to it — apply the same Label/Href/Icon/Authorization extraction as Step 2.

                    - _NoAuth project_*: render ONLY what the context assigns to the Profile region. No `<AuthorizeView>` anywhere in this file. If Profile currently has zero qualifying items, leave the scaffolded placeholder as-is — do not invent content.
                    - _Auth project_*: render ONLY what the context assigns to the Profile region. If (and only if) the context includes auth-gated items, apply `<AuthorizeView>` gating to those specific items.

                    Do not add Login/Register/Manage/Logout by default, even in Auth projects. Only add those if they are present in the provided context (or explicitly modeled into the Profile region).

                    If the existing Profile menu file already contains a fixed auth block (e.g. Login/Register vs Logout) from past runs, do not treat that as a requirement. Keep or remove it only if the user's current context requires it; otherwise preserve existing content and only add the explicitly described items.

                    ```
                    <AuthorizeView>
                    <Authorized>
                    <UserMenu>
                    <Trigger>...</Trigger>
                    <ChildContent>
                    <MudStack Spacing="0">
                    <!-- one item per modeled Profile nav link -->
                    <!-- fixed Logout form, always last -->
                    </MudStack>
                    </ChildContent>
                    </UserMenu>
                    </Authorized>
                    </AuthorizeView>

                    <AuthorizeView>
                    <NotAuthorized>
                    <UserMenu Title="Account">
                    <Trigger>...</Trigger>
                    <ChildContent>
                    <MudStack Spacing="0">
                    <!-- fixed Login + Register buttons -->
                    </MudStack>
                    </ChildContent>
                    </UserMenu>
                    </NotAuthorized>
                    </AuthorizeView>
                    ```

                    - **Modeled Profile items** go inside the first block's `ChildContent`, one per item, following the project's existing item pattern (e.g. `<MudButton Href="..." Variant="Variant.Text" Color="Color.Inherit" FullWidth="true">Label</MudButton>`). Gate an individual item further with `<AuthorizeView Roles="...">`/`Policy="..."` only if that specific item's own context said so (nested inside the outer `Authorized` block) — same Step 2 rules as Sider. If Profile currently has zero qualifying items, the Authorized block's `ChildContent` still gets just the fixed Logout form below (never left completely empty in an Auth project).
                    - **The fixed Logout form** — always the last entry in the Authorized block's `ChildContent`, never gated further, never removed, never replaced with an `OnClick` handler or client-side auth call:

                    ```
                    <form method="post" action="/Account/Logout">
                    <AntiforgeryToken />
                    <input type="hidden" name="ReturnUrl" value="@ReturnUrl" />
                    <MudButton ButtonType="ButtonType.Submit" Variant="Variant.Text" Color="Color.Inherit" FullWidth="true">
                    Logout
                    </MudButton>
                    </form>
                    ```

                    This requires a `ReturnUrl` code-behind member — if not already present, add to the file's `@code` block:

                    ```
                    [CascadingParameter]
                    private HttpContext? HttpContext { get; set; }

                    private string? ReturnUrl => HttpContext is null ? null : $"{HttpContext.Request.Path}{HttpContext.Request.QueryString}";
                    ```

                    - **The fixed Login/Register block** — always the entire content of the `NotAuthorized` block's `UserMenu` (`Title="Account"`), never gated further, never removed:

                    ```
                    <MudButton Href="/Account/Login" Variant="Variant.Text" Color="Color.Inherit" FullWidth="true">Login</MudButton>
                    <MudButton Href="/Account/Register" Variant="Variant.Text" Color="Color.Inherit" FullWidth="true">Register</MudButton>
                    ```

                    ### Region source-of-truth and "mandatory" sync (CRITICAL)

                    Only add/ensure items that the context/model explicitly assigns to the Profile region.

                    Rules:

                    - If nothing is assigned to Profile, leave the file unchanged.

                    - Do not mirror Sider/Header/Footer items into the Profile menu by convention.
                    - Only prevent duplicates within the Profile menu itself.
                    - _WASM Auth specifics_*: in a hosted WASM Auth project, verify whether this Profile file is duplicated between the host project (static-SSR, used by the Account pages) and the `.Client` project (interactive, used by `MainLayout`/`MainLayoutHeader`) — don't assume a fixed filename pair, confirm by locating both. If duplicated, keep both copies' modeled items in sync.
                   
