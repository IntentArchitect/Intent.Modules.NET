                    ## Step 8 — CRITICAL: Ensure Idempotence (No Duplicate Items)

                    When this skill is run repeatedly (or when it is run after a menu file already contains some items), it MUST NOT create duplicates.

                    Before inserting any new menu item into a region file, you MUST check whether an equivalent item already exists in that same file/region.

                    ### De-duplication key (preferred order)

                    Treat a menu item as a duplicate if **any** of the following match:

                    1. **Same route/href** (preferred):
                    - `Href="/Account/Login"` matches any existing item with `Href` equal to `/Account/Login`.
                    - Match case-insensitively and ignoring a trailing `/`.
                    2. **Same label** (fallback):
                    - Visible text label matches case-insensitively after trimming whitespace (e.g. `Login` == `login`).

                    ### De-duplication scope

                    - De-duplicate **within the same menu surface file only** (Header vs Sider vs Footer vs Profile are independent).
                    - De-duplicate **within the same authorization block** if the file contains multiple states (e.g. `<Authorized>` vs `<NotAuthorized>`). Never add the same route twice within the same block.

                    ### Mandatory behavior

                    - If a duplicate exists, do NOT add another copy.
                    - If the context explicitly lists an item that already exists, preserve the existing one (do not remove/recreate it).

