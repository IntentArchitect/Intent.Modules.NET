                    name: blazor-app-menu
                    description: Populates MainLayoutHeader.razor, MainLayoutSider.razor, MainLayoutFooter.razor, and the Profile menu component (e.g. MainLayoutProfile.razor), either from a natural-language description of the app's menu structure or from modeled Navigation Target Ends (Layout Placement -> Regions), gating individual items by authentication/roles/policy only when the project actually has the Authentication module installed. Also keeps MainLayout.razor's Header/Sider/Footer component references in sync whenever a region is added or removed. Use when asked to add, change, or regenerate navigation/menu items, sider links, header links, or the profile/account menu in a Blazor project using MainLayout/MainLayoutHeader/MainLayoutSider/MainLayoutFooter/Profile-Menu, and whenever a Navigation Target End on MainLayout was added, changed, or removed, or a Sider/Header/Footer region itself was added or removed.
