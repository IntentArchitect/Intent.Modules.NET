                    ## Forbidden

                    - Reintroducing a shared nav-item model (`NavItem` record, `AppNav` static class, or any `Items` parameter feeding a generic loop) — every menu surface is literal markup by design.
                    - Reintroducing a `<MudDrawer Open="..." OpenChanged="...">` wrapper around the Sider's `<MudNavMenu>`, or `OnClick`/`OnToggle` `EventCallback` parameters on the Header's drawer-toggle button or `ThemeToggle` — these belonged to an older scaffold generation and no longer exist in the code-behind.
                    - Adding `<AuthorizeView>`, `AddAuthorizationCore()`, or `AddCascadingAuthenticationState()` to a project that doesn't already have them, in order to make a described role/policy requirement "work".
                    - Adding an `<AuthorizeView>` split to `MainLayoutHeader.razor` for the Profile slot — that branching lives inside the Profile file itself (Step 6), never in the Header.
                    - Adding a `<NotAuthorized>` fragment to a gated **nav item** (Sider/Header/Footer link, or an individual modeled Profile item) — items should disappear, not show a fallback message.

                    - Passing `Roles` as anything other than a single comma-delimited string to `AuthorizeView` (it is not a `string[]` parameter).
                    - Replacing the WASM `.Client` Profile file's plain link/POST-form pattern with a client-side auth call.
                    - Inventing routes, roles, or policies that weren't in the given context.
                    - Removing existing menu items the new context doesn't mention (treat as additive unless told otherwise).
                    - Inventing account/auth menu items (Login/Register/Manage/Logout) that aren't in the context.

                    - Adding or removing the header's Profile-component reference based on whether the Profile menu has qualifying items — the reference is present whenever the Profile file exists at all, full stop.
                    - Assigning items to the Profile region by convention/mirroring rather than because the context/model explicitly placed them there.
                    - Inventing or maintaining a `ManageLayout.razor` `<aside>` nav duplicate — that mechanism no longer exists in current-generation projects.
                    - Rewriting, reordering, or restyling any part of `MainLayout.razor` beyond adding/removing a `<MainLayoutHeader/>`/`<MainLayoutSider/>`/`<MainLayoutFooter/>` reference to match which region files currently exist — its provider components, wrapper element(s), CSS classes, and `@Body` placement are not this skill's concern.
                    - Adding a `<MainLayoutProfile />` reference to `MainLayout.razor` — that reference belongs only in `MainLayoutHeader.razor`.
                    - Removing `<MainLayoutHeader />` or `<MainLayoutSider />` from `MainLayout.razor` — those are core and always present.

