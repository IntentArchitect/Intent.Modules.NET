using EntityFrameworkCore.SqlServer.EF11.Domain.PkDataSources;
using EntityFrameworkCore.SqlServer.EF11.Domain.Repositories;
using EntityFrameworkCore.SqlServer.EF11.Domain.Repositories.PkDataSources;
using EntityFrameworkCore.SqlServer.EF11.Infrastructure.Persistence;
using Intent.RoslynWeaver.Attributes;

[assembly: DefaultIntentManaged(Mode.Fully)]
[assembly: IntentTemplate("Intent.EntityFrameworkCore.Repositories.Repository", Version = "1.0")]

namespace EntityFrameworkCore.SqlServer.EF11.Infrastructure.Repositories.PkDataSources
{
    [IntentManaged(Mode.Merge, Signature = Mode.Fully)]
    public class CompKeyAutoGeneratedDataSourceEntityRepository : RepositoryBase<CompKeyAutoGeneratedDataSourceEntity, CompKeyAutoGeneratedDataSourceEntity, ApplicationDbContext>, ICompKeyAutoGeneratedDataSourceEntityRepository
    {
        public CompKeyAutoGeneratedDataSourceEntityRepository(ApplicationDbContext dbContext) : base(dbContext)
        {
        }

        public async Task<CompKeyAutoGeneratedDataSourceEntity?> FindByIdAsync(
            (long Id1, long Id2) id,
            CancellationToken cancellationToken = default)
        {
            return await FindAsync(x => x.Id1 == id.Id1 && x.Id2 == id.Id2, cancellationToken);
        }

        public async Task<CompKeyAutoGeneratedDataSourceEntity?> FindByIdAsync(
            (long Id1, long Id2) id,
            Func<IQueryable<CompKeyAutoGeneratedDataSourceEntity>, IQueryable<CompKeyAutoGeneratedDataSourceEntity>> queryOptions,
            CancellationToken cancellationToken = default)
        {
            return await FindAsync(x => x.Id1 == id.Id1 && x.Id2 == id.Id2, queryOptions, cancellationToken);
        }
    }
}